function buildCommonPasswordSet(): ReadonlySet<string> {
  const set = new Set<string>();
  for (const pwd of BASE_COMMON_PASSWORDS) {
    set.add(pwd.normalize('NFKC').toLowerCase());
  }
  for (const word of COMMON_WORDS) {
    for (const suffix of COMMON_SUFFIXES) {
      const combined = `${word}${suffix}`;
      if (combined.length >= 12) {
        set.add(combined.normalize('NFKC').toLowerCase());
      }
    }
  }
  return set;
}

export const COMMON_PASSWORDS: ReadonlySet<string> = buildCommonPasswordSet();
